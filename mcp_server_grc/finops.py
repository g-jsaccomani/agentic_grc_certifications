USD_TO_BRL_RATE = 5.70


class AgentFinOpsRecord:
    def __init__(
        self,
        agent_id: str,
        name: str,
        category: str,
        model_key: str,
        invocations: int = 0,
        prompt_tokens: int = 0,
        cached_tokens: int = 0,
        completion_tokens: int = 0,
    ):
        self.agent_id = agent_id
        self.name = name
        self.category = category
        self.model_key = model_key
        self.invocations = invocations
        self.prompt_tokens = prompt_tokens
        self.cached_tokens = cached_tokens
        self.completion_tokens = completion_tokens

    @property
    def total_tokens(self) -> int:
        return self.prompt_tokens + self.cached_tokens + self.completion_tokens

    @property
    def cost_usd(self) -> float:
        pricing = MODEL_PRICING.get(self.model_key, MODEL_PRICING["gemini-2.5-flash"])
        cost = (
            self.prompt_tokens * pricing["prompt_rate"]
            + self.cached_tokens * pricing["cached_rate"]
            + self.completion_tokens * pricing["completion_rate"]
        ) / 1_000_000
        return round(cost, 4)

    @property
    def cost_brl(self) -> float:
        return round(self.cost_usd * USD_TO_BRL_RATE, 2)

    @property
    def savings_usd(self) -> float:
        """Savings generated by Gemini Context Caching vs uncached re-reading."""
        pricing = MODEL_PRICING.get(self.model_key, MODEL_PRICING["gemini-2.5-flash"])
        uncached_cost = (self.cached_tokens * pricing["prompt_rate"]) / 1_000_000
        cached_cost = (self.cached_tokens * pricing["cached_rate"]) / 1_000_000
        return round(max(0.0, uncached_cost - cached_cost), 4)

    def to_dict(self) -> Dict[str, Any]:
        pricing = MODEL_PRICING.get(self.model_key, MODEL_PRICING["gemini-2.5-flash"])
        return {
            "agent_id": self.agent_id,
            "name": self.name,
            "category": self.category,
            "model": pricing["name"],
            "model_key": self.model_key,
            "invocations": self.invocations,
            "prompt_tokens": self.prompt_tokens,
            "cached_tokens": self.cached_tokens,
            "completion_tokens": self.completion_tokens,
            "total_tokens": self.total_tokens,
            "cost_usd": self.cost_usd,
            "cost_brl": self.cost_brl,
            "savings_usd": self.savings_usd,
        }


