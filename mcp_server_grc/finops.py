    def record_usage(
        self,
        agent_id: str,
        prompt_tokens: int,
        completion_tokens: int,
        cached_tokens: int = 0,
        model_key: str = "gemini-2.5-flash",
        name: Optional[str] = None,
        category: Optional[str] = None,
    ):
        if agent_id not in self.records:
            self.records[agent_id] = AgentFinOpsRecord(
                agent_id=agent_id,
                name=name or agent_id.replace("-", " ").title(),
                category=category or "Subagente Dinâmico",
                model_key=model_key,
            )
        rec = self.records[agent_id]
        rec.invocations += 1
        rec.prompt_tokens += prompt_tokens
        rec.cached_tokens += cached_tokens
        rec.completion_tokens += completion_tokens

    def get_summary(self) -> Dict[str, Any]:
        agents_data = [rec.to_dict() for rec in self.records.values()]
        
        total_prompt = sum(r["prompt_tokens"] for r in agents_data)
        total_cached = sum(r["cached_tokens"] for r in agents_data)
        total_completion = sum(r["completion_tokens"] for r in agents_data)
        total_tokens = total_prompt + total_cached + total_completion
        total_invocations = sum(r["invocations"] for r in agents_data)
        
        total_cost_usd = round(sum(r["cost_usd"] for r in agents_data), 4)
        total_cost_brl = round(total_cost_usd * USD_TO_BRL_RATE, 2)
        total_savings_usd = round(sum(r["savings_usd"] for r in agents_data), 4)
        total_savings_brl = round(total_savings_usd * USD_TO_BRL_RATE, 2)
        
        cache_hit_ratio = round((total_cached / (total_prompt + total_cached) * 100) if (total_prompt + total_cached) > 0 else 0, 1)
        cost_per_control_usd = round(total_cost_usd / 93, 4)

        return {
            "summary": {
                "total_cost_usd": total_cost_usd,
                "total_cost_brl": total_cost_brl,
                "total_savings_usd": total_savings_usd,
                "total_savings_brl": total_savings_brl,
                "total_tokens": total_tokens,
                "total_prompt_tokens": total_prompt,
                "total_cached_tokens": total_cached,
                "total_completion_tokens": total_completion,
                "total_invocations": total_invocations,
                "cache_hit_ratio_percent": cache_hit_ratio,
                "cost_per_control_usd": cost_per_control_usd,
                "usd_to_brl_rate": USD_TO_BRL_RATE,
                "monthly_quota_usd": 50.00,
                "quota_used_percent": round((total_cost_usd / 50.00) * 100, 1),
                "timestamp": datetime.now(timezone.utc).isoformat(),
            },
            "agents": agents_data,
            "phases": self.phase_metrics,
            "pricing_reference": MODEL_PRICING,
        }


